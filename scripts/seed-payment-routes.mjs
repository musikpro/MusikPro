import { randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { kitVersionLabel } from "./lib/version.mjs";
const root = process.cwd();
const configPath = path.join(root, "africa-saas.config.json");
if (!fs.existsSync(configPath)) throw new Error("Run npm run setup first.");
const c = JSON.parse(fs.readFileSync(configPath, "utf8"));
const esc = s => `'${String(s).replaceAll("'", "''")}'`;
const enabled = Array.isArray(c.providers) ? c.providers : [];
if (!enabled.length) {
  fs.mkdirSync(path.join(root,"generated"), {recursive:true});
  fs.writeFileSync(path.join(root,"generated/payment-routes.sql"), "-- Payments disabled: no provider routes to generate.\n");
  console.log("✓ Payments disabled / optional: no payment routes generated.");
  process.exit(0);
}
const rows = enabled.map((provider, index) => ({ provider, priority: (index + 1) * 10 }));
const sql = [
  `-- Generated by Africa SaaS Kit ${kitVersionLabel}. Review before applying to production.`,
  "BEGIN;",
  ...rows.map(r => `INSERT INTO payment_provider_configs (id, provider, enabled, priority, mode, config, updated_at) VALUES (${esc(cryptoRandom())}, ${esc(r.provider)}, true, ${r.priority}, 'sandbox', '{}'::jsonb, NOW()) ON CONFLICT (provider) DO UPDATE SET enabled = EXCLUDED.enabled, priority = EXCLUDED.priority, updated_at = NOW();`),
  ...rows.map(r => `INSERT INTO payment_country_routes (id, country, provider, enabled, priority, currencies, methods, updated_at) VALUES (${esc(cryptoRandom())}, ${esc(c.country)}, ${esc(r.provider)}, true, ${r.priority}, ${esc(JSON.stringify([c.currency]))}::jsonb, ${esc(JSON.stringify(c.methods))}::jsonb, NOW()) ON CONFLICT (country, provider) DO UPDATE SET enabled = EXCLUDED.enabled, priority = EXCLUDED.priority, currencies = EXCLUDED.currencies, methods = EXCLUDED.methods, updated_at = NOW();`),
  "COMMIT;",
  ""
].join("\n");
function cryptoRandom(){ return `seed_${randomUUID()}`; }
fs.mkdirSync(path.join(root,"generated"), {recursive:true});
fs.writeFileSync(path.join(root,"generated/payment-routes.sql"), sql);
console.log("✓ generated/payment-routes.sql created");
console.log("Review the SQL and apply it only after your Drizzle migrations created the payment routing tables.");
